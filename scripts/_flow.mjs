import { chromium } from "@playwright/test";
const out = process.argv[2];
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: "es-CO" });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:3100/entrenar", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.getByRole("button", { name: /Iniciar Torso A/ }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/flow-1.png` });
const w = page.getByLabel("Peso serie 1 en lb");
await w.fill("70");
await page.getByLabel("Repeticiones serie 1").fill("12");
await page.getByLabel("Marcar serie 1 como hecha").click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/flow-2.png` });
await page.getByRole("button", { name: "No puedo hacer este" }).first().click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/flow-3.png` });
console.log(errors.slice(0, 5).join("\n"));
await browser.close();
